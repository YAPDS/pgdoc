#!/usr/bin/env python3
"""Import PostgreSQL's chunked DocBook HTML into Hugo content."""

import argparse
from html import unescape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import shutil
from urllib.parse import urlsplit

SITE = Path(__file__).resolve().parents[1]
BODY = re.compile(r"<body\b[^>]*>(.*?)</body\s*>", re.IGNORECASE | re.DOTALL)
ASSETS = {".svg", ".png", ".gif", ".jpg", ".jpeg", ".webp", ".css"}
VERSION = re.compile(r"(?:devel|[1-9][0-9]*(?:\.[0-9]+)?)\Z")
MARKER = "<!-- Generated by scripts/import_postgres_html.py. -->"


class TitleParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.in_title = False
        self.chunks = []

    def handle_starttag(self, tag, attrs):
        if tag.lower() == "title":
            self.in_title = True

    def handle_endtag(self, tag):
        if tag.lower() == "title":
            self.in_title = False

    def handle_data(self, data):
        if self.in_title:
            self.chunks.append(data)


class TocParser(HTMLParser):
    """Read DocBook's first div.toc as an ordered link tree."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.div_depth = 0
        self.toc_depth = None
        self.done = False
        self.dl_depth = 0
        self.in_dt = False
        self.link = None
        self.nodes = []
        self.parents = {}

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "div":
            self.div_depth += 1
            if not self.done and self.toc_depth is None and "toc" in attrs.get("class", "").split():
                self.toc_depth = self.div_depth
        if self.toc_depth is None or self.done:
            return
        if tag == "dl":
            self.dl_depth += 1
        elif tag == "dt":
            self.in_dt = True
        elif tag == "a" and self.in_dt and self.dl_depth > 0:
            self.link = {"href": attrs.get("href", ""), "text": []}

    def handle_endtag(self, tag):
        if self.toc_depth is not None and not self.done:
            if tag == "a" and self.link is not None:
                href = self.link["href"]
                page = urlsplit(href).path
                if page.endswith(".html") and "/" not in page:
                    node = {
                        "title": " ".join("".join(self.link["text"]).split()),
                        "href": href,
                        "page": page,
                        "children": [],
                    }
                    parent = self.parents.get(self.dl_depth - 1)
                    (parent["children"] if parent else self.nodes).append(node)
                    self.parents[self.dl_depth] = node
                self.link = None
            elif tag == "dt":
                self.in_dt = False
            elif tag == "dl":
                self.parents.pop(self.dl_depth, None)
                self.dl_depth -= 1
            elif tag == "div" and self.div_depth == self.toc_depth:
                self.done = True
        if tag == "div":
            self.div_depth -= 1

    def handle_data(self, data):
        if self.link is not None:
            self.link["text"].append(data)


def parse_toc(raw: str):
    parser = TocParser()
    parser.feed(raw)
    return parser.nodes


def build_navigation(source: Path, html_files):
    roots = parse_toc((source / "index.html").read_text(encoding="utf-8"))
    # The book index lists parts and chapters. Each chapter page supplies its
    # own section tree, including reference entries and subsection pages.
    for part in roots:
        candidates = part["children"] or [part]
        for chapter in candidates:
            if chapter["children"]:
                continue
            page = source / chapter["page"]
            if page.is_file():
                chapter["children"] = parse_toc(page.read_text(encoding="utf-8"))

    parents = {"index.html": []}

    def walk(nodes, ancestors):
        for node in nodes:
            parents.setdefault(node["page"], ancestors)
            walk(node["children"], ancestors + [node["page"]])

    walk(roots, [])
    # Some pages are linked only from a subsection. DocBook's rel=up header
    # identifies their parent even when the book's TOC stops at that depth.
    up_links = {}
    up_pattern = re.compile(r'<link\s+[^>]*rel="up"[^>]*href="([^"#]+)"', re.IGNORECASE)
    for page in html_files:
        if page.name in parents:
            continue
        match = up_pattern.search(page.read_text(encoding="utf-8")[:4096])
        if match:
            up_links[page.name] = match.group(1)

    def resolve(page, visiting):
        if page in parents:
            return parents[page]
        if page in visiting or page not in up_links:
            return []
        up = up_links[page]
        ancestry = resolve(up, visiting | {page}) + [up]
        parents[page] = ancestry
        return ancestry

    for page in up_links:
        resolve(page, set())
    return {"sections": roots, "parents": parents}


def extract_page(raw: str, source: Path):
    title_parser = TitleParser()
    title_parser.feed(raw)
    title = unescape("".join(title_parser.chunks)).strip()
    match = BODY.search(raw)
    if not title or not match:
        raise ValueError(f"Expected title and body in {source}")
    return title, match.group(1).strip()


def import_docs(source: Path, version: str, language: str = "en"):
    if not VERSION.fullmatch(version):
        raise ValueError("Version must be 'devel' or a PostgreSQL major version")
    if language not in ("en", "zh"):
        raise ValueError("Language must be 'en' or 'zh'")
    if not source.is_dir():
        raise FileNotFoundError(source)
    html_files = sorted(source.glob("*.html"))
    if not html_files or not (source / "index.html").is_file():
        raise ValueError(f"No chunked manual with index.html found in {source}")

    content_root = SITE / "content" / language
    public_prefix = "" if language == "en" else "zh/"
    content_dir = content_root / "postgresql" / version
    asset_dir = SITE / "static" / public_prefix / "postgresql" / version
    content_dir.mkdir(parents=True, exist_ok=True)
    asset_dir.mkdir(parents=True, exist_ok=True)
    expected_content = set()
    expected_assets = set()

    for page in html_files:
        title, body = extract_page(page.read_text(encoding="utf-8"), page)
        target = content_dir / ("_index.html" if page.name == "index.html" else page.name)
        fields = [f"title = {json.dumps(title, ensure_ascii=False)}", "upstream = true", f"source_version = {json.dumps(version)}"]
        if page.name == "index.html":
            fields.append(f"weight = {1000 if version == 'devel' else 100 - int(version.split('.')[0])}")
        else:
            fields.append(f"url = {json.dumps(f'/{public_prefix}postgresql/{version}/{page.name}')}")
        content = "+++\n" + "\n".join(fields) + "\n+++\n\n" + MARKER + "\n\n" + body + "\n"
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")
        expected_content.add(target)

    for asset in source.iterdir():
        if asset.is_file() and asset.suffix.lower() in ASSETS:
            target = asset_dir / asset.name
            shutil.copy2(asset, target)
            expected_assets.add(target)

    for pattern in ("*.md", "*.html"):
        for old in content_dir.glob(pattern):
            if old not in expected_content and MARKER in old.read_text(encoding="utf-8"):
                old.unlink()
    for old in asset_dir.iterdir():
        if old.is_file() and old not in expected_assets:
            old.unlink()
    navigation = json.dumps(build_navigation(source, html_files), ensure_ascii=False, separators=(",", ":")) + "\n"
    data_nav = SITE / "data" / "manual_nav"
    if language == "zh":
        data_nav /= "zh"
    for nav_file in (data_nav / f"{version}.json",
                     SITE / "static" / public_prefix / "manual-nav" / f"{version}.json"):
        nav_file.parent.mkdir(parents=True, exist_ok=True)
        nav_file.write_text(navigation, encoding="utf-8")
    print(f"Imported PostgreSQL {version} ({language}): {len(html_files)} pages, {len(expected_assets)} assets")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--language", choices=("en", "zh"), default="en")
    args = parser.parse_args()
    import_docs(args.source, args.version, args.language)


if __name__ == "__main__":
    main()
